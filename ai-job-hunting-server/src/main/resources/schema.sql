-- PostgreSQL 16+: run once in a new ai_job database using psql --single-transaction.
-- Tables are created in the current schema; no database is created or replaced.
create table msg_session
(
    id                           bigint GENERATED BY DEFAULT AS IDENTITY
        primary key,
    msg_context                  text null,
    ai_type                      int null,
    status                       int null,
    user_id                      bigint null,
    session_key                  varchar(64) null,
    is_active                    boolean default false null,
    created_id                   bigint null,
    created_date                 timestamp without time zone null,
    updated_id                   bigint null,
    updated_date                 timestamp without time zone null
);

create table "order"
(
    id                           bigint not null
        primary key,
    status                       int null,
    user_id                      bigint null,
    type                         int null,
    is_active                    boolean default false null,
    created_id                   bigint null,
    created_date                 timestamp without time zone null,
    updated_id                   bigint null,
    updated_date                 timestamp without time zone null,
    price                        decimal(10, 4) default 0.0000 null
);

create table user_ai_config
(
    id                           bigint GENERATED BY DEFAULT AS IDENTITY
        primary key,
    user_id                      bigint not null,
    provider                     int default 0 not null,
    api_format                   varchar(16) default 'OPENAI' not null CHECK (api_format IN ('OPENAI', 'ANTHROPIC')),
    max_tokens                   int default 1024 not null CHECK (max_tokens BETWEEN 1 AND 128000),
    model_name                   varchar(128) null,
    api_key                      varchar(255) not null,
    base_url                     varchar(1024) null,
    completions_path             varchar(255) null,
    timeout                      int default 30 null,
    test_passed                  smallint default 0 not null,
    status                       smallint default 1 not null,
    is_active                    boolean default false null,
    created_id                   bigint null,
    created_date                 timestamp without time zone null,
    updated_id                   bigint null,
    updated_date                 timestamp without time zone null,
    user_prompt                  text null
);

create index idx_status
    on user_ai_config (status);

create index idx_user_id
    on user_ai_config (user_id);

create table user_info
(
    id                           bigint GENERATED BY DEFAULT AS IDENTITY
        primary key,
    phone                        varchar(11) null,
    email                        varchar(56) null,
    preference                   text null,
    is_active                    boolean default false null,
    created_id                   bigint null,
    created_date                 timestamp without time zone null,
    updated_id                   bigint null,
    updated_date                 timestamp without time zone null,
    unique_id                    varchar(32) null,
    ai_seat_status               int null,
    invite_code                  varchar(64) null,
    bind_invite_code             varchar(64) null
);

create table user_invites
(
    id                           bigint GENERATED BY DEFAULT AS IDENTITY
        primary key,
    invite_code                  varchar(64) not null,
    to_inviter_user_id           bigint not null,
    be_invitee_user_id           bigint not null,
    be_invitee_username          varchar(64) null,
    status                       int not null,
    is_active                    boolean default false null,
    created_id                   bigint null,
    created_date                 timestamp without time zone null,
    updated_id                   bigint null,
    updated_date                 timestamp without time zone null,
    constraint be_invitee_user_id
        unique (be_invitee_user_id)
);

create table user_product
(
    id                           bigint GENERATED BY DEFAULT AS IDENTITY
        primary key,
    user_id                      bigint null,
    order_id                     bigint null,
    product_id                   bigint null,
    product_type                 varchar(64) null,
    period_of_validity_start_time timestamp without time zone null,
    period_of_validity_end_time  timestamp without time zone null,
    is_active                    boolean default false null,
    created_id                   bigint null,
    created_date                 timestamp without time zone null,
    updated_id                   bigint null,
    updated_date                 timestamp without time zone null
);

create table user_resume
(
    id                           bigint GENERATED BY DEFAULT AS IDENTITY
        primary key,
    user_id                      bigint null,
    resume_content               text null,
    resume_url                   varchar(256) null,
    is_active                    boolean default false null,
    created_id                   bigint null,
    created_date                 timestamp without time zone null,
    updated_id                   bigint null,
    updated_date                 timestamp without time zone null,
    oss_file_name                varchar(64) null,
    preset_problem               text null,
    resume_id                    varchar(64) null
);

create table user_trial
(
    id                           bigint GENERATED BY DEFAULT AS IDENTITY
        primary key,
    user_id                      bigint null,
    product_type                 int null,
    trial_count                  int null,
    is_active                    boolean default false null,
    created_id                   bigint null,
    created_date                 timestamp without time zone null,
    updated_id                   bigint null,
    updated_date                 timestamp without time zone null,
    "desc"                       varchar(64) null
);

